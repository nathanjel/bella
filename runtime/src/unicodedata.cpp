// _ucd_call(name, ...): the prelude's way in. `old` is UCD_Check(self): the 3.2.0 database.
Ref dispatch(Args a) {
    const std::string& op = as_str(a.pos(0))->text;
    auto arg = [&a](std::size_t i) { return a.pos(i + 1); };
    auto flag = [&a](std::size_t i) { return truth(a.pos(i + 1)); };
    if (op == "decimal") return int_from_i64(decimal(code_arg(arg(0)), flag(1)));   // (code, old): -1 for none
    if (op == "digit") return int_from_i64(unicodetype::_PyUnicode_ToDigit(code_arg(arg(0))));   // (code): Py_UNICODE_TODIGIT
    if (op == "numeric") return float_ref(numeric(code_arg(arg(0)), flag(1)));   // (code, old): -1.0 for none
    if (op == "category") return text(category(code_arg(arg(0)), flag(1)));
    if (op == "bidirectional") return text(bidirectional(code_arg(arg(0)), flag(1)));
    if (op == "combining") return int_from_i64(combining(code_arg(arg(0)), flag(1)));
    if (op == "mirrored") return int_from_i64(mirrored(code_arg(arg(0)), flag(1)));
    if (op == "east_asian_width") return text(east_asian_width(code_arg(arg(0)), flag(1)));
    if (op == "decomposition") return str_new(decomposition(code_arg(arg(0)), flag(1)));
    if (op == "normalize") return normalize(flag(0), arg(1), arg(2));          // (old, form, str)
    if (op == "is_normalized") return is_normalized(flag(0), arg(1), arg(2));  // (old, form, str)
    if (op == "name") return name_impl(flag(1), code_arg(arg(0)));                  // (code, old): None for none
    if (op == "lookup") return lookup_impl(flag(1), bytes_data(arg(0)));            // (name as bytes, old): None for none
    if (op == "block") return text(block(code_arg(arg(0))));
    if (op == "grapheme_cluster_break") return text(_PyUnicode_GraphemeBreakNames[_getrecord_ex(code_arg(arg(0)))->grapheme_cluster_break]);
    if (op == "indic_conjunct_break") return text(_PyUnicode_IndicConjunctBreakNames[_getrecord_ex(code_arg(arg(0)))->incb]);
    if (op == "extended_pictographic") return Ref::steal(boolean(_getrecord_ex(code_arg(arg(0)))->ext_pict != 0));
    if (op == "isxidstart") return Ref::steal(boolean(unicodetype::_PyUnicode_IsXidStart(code_arg(arg(0))) != 0));
    if (op == "isxidcontinue") return Ref::steal(boolean(unicodetype::_PyUnicode_IsXidContinue(code_arg(arg(0))) != 0));
    if (op == "next_break") {                    // (str, (start, pos, end, gcb, ep_state, incb_state, ri_flag)) -> (break or -1, state)
        auto& st = static_cast<Tuple*>(arg(1).object())->items;
        _PyGraphemeBreak iter{as_str(arg(0)), i64_arg(st[0]), i64_arg(st[1]), i64_arg(st[2]), static_cast<int>(i64_arg(st[3])),
                              static_cast<ExtPictState>(i64_arg(st[4])), static_cast<InCBState>(i64_arg(st[5])), i64_arg(st[6]) != 0};
        Py_ssize_t at = _Py_NextGraphemeBreak(&iter);
        Ref b = int_from_i64(at), s0 = int_from_i64(iter.start), s1 = int_from_i64(iter.pos), s2 = int_from_i64(iter.end), s3 = int_from_i64(iter.gcb),
            s4 = int_from_i64(iter.ep_state), s5 = int_from_i64(iter.incb_state), s6 = int_from_i64(iter.ri_flag ? 1 : 0);
        Ref state = tuple_new({s0.get(), s1.get(), s2.get(), s3.get(), s4.get(), s5.get(), s6.get()});
        return tuple_new({b.get(), state.get()});
    }
    if (op == "length") return int_from_i64(static_cast<std::int64_t>(as_str(arg(0))->length));   // PyUnicode_GET_LENGTH
    if (op == "substring") {                     // (str, start, end): PyUnicode_Substring
        const Str* s = as_str(arg(0));
        std::int64_t start = i64_arg(arg(1)), end = i64_arg(arg(2));
        if (start == 0 && end >= static_cast<std::int64_t>(s->length)) return from_object(arg(0));   // unicode_result_unchanged
        std::u32string out;
        for (std::int64_t i = start; i < end; ++i) out += s->at(static_cast<std::size_t>(i));
        return str_from_codepoints(out);
    }
    if (op == "capsule") {                       // unicodedata_create_capi: the capsule, which no Python code can open
        static bool presented = false;
        ClassObject* c = bella::capsule_class();
        if (!presented) {
            auto* f = new Builtin("__repr__", bella::capsule_repr, Obj{}, Binding::Method);
            f->owner = c;
            f->flags |= IMMORTAL;
            c->attrs.set(intern("__repr__"), Obj::of(f));
            presented = true;
        }
        return own(new_instance(c));
    }
    throw NotImplemented("unicodedata primitive " + op);
}
