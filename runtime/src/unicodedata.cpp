// For Hangul decomposition
#define SBase   0xAC00
#define LBase   0x1100
#define VBase   0x1161
#define TBase   0x11A7
#define LCount  19
#define VCount  21
#define TCount  28
#define NCount  (VCount*TCount)
#define SCount  (LCount*NCount)

std::string decomposition(Py_UCS4 c, bool old)
{
    char decomp[256];
    int code, index, count;
    size_t i;
    unsigned int prefix_index;

    code = (int)c;

    if (old) {
        const change_record *o = get_old_record(old, c);
        if (o->category_changed == 0)
            return ""; /* unassigned */
    }

    // Hangul Decomposition.
    // See section 3.12.2, "Hangul Syllable Decomposition"
    // https://www.unicode.org/versions/latest/core-spec/chapter-3/#G56669
    if (SBase <= code && code < (SBase + SCount)) {
        int SIndex = code - SBase;
        int L = LBase + SIndex / NCount;
        int V = VBase + (SIndex % NCount) / TCount;
        int T = TBase + SIndex % TCount;
        if (T != TBase) {
            std::snprintf(decomp, sizeof(decomp),
                          "%04X %04X %04X", L, V, T);
        }
        else {
            std::snprintf(decomp, sizeof(decomp),
                          "%04X %04X", L, V);
        }
        return decomp;
    }

    if (code < 0 || code >= 0x110000)
        index = 0;
    else {
        index = decomp_index1[(code>>DECOMP_SHIFT)];
        index = decomp_index2[(index<<DECOMP_SHIFT)+
                             (code&((1<<DECOMP_SHIFT)-1))];
    }

    /* high byte is number of hex bytes (usually one or two), low byte
       is prefix code (from*/
    count = decomp_data[index] >> 8;

    /* Based on how index is calculated above and decomp_data is generated
       from Tools/unicode/makeunicodedata.py, it should not be possible
       to overflow decomp_prefix. */
    prefix_index = decomp_data[index] & 255;

    /* copy prefix */
    i = std::strlen(decomp_prefix[prefix_index]);
    std::memcpy(decomp, decomp_prefix[prefix_index], i);

    while (count-- > 0) {
        if (i)
            decomp[i++] = ' ';
        std::snprintf(decomp + i, sizeof(decomp) - i, "%04X",
                      decomp_data[++index]);
        i += std::strlen(decomp + i);
    }
    return std::string(decomp, i);
}

static void
get_decomp_record(bool old, Py_UCS4 code,
                  int *index, int *prefix, int *count)
{
    if (code >= 0x110000) {
        *index = 0;
    }
    else if (old
             && get_old_record(old, code)->category_changed==0) {
        /* unassigned in old version */
        *index = 0;
    }
    else {
        *index = decomp_index1[(code>>DECOMP_SHIFT)];
        *index = decomp_index2[(*index<<DECOMP_SHIFT)+
                               (code&((1<<DECOMP_SHIFT)-1))];
    }

    /* high byte is number of hex bytes (usually one or two), low byte
       is prefix code (from*/
    *count = decomp_data[*index] >> 8;
    *prefix = decomp_data[*index] & 255;

    (*index)++;
}

/* Small combining runs are usually cheaper with insertion sort. */
#define CANONICAL_ORDERING_COUNTING_SORT_THRESHOLD 20

static void
canonical_ordering_sort_insertion(std::u32string& data,
                                  Py_ssize_t start, Py_ssize_t end)
{
    for (Py_ssize_t i = start + 1; i < end; i++) {
        Py_UCS4 code = data[i];
        unsigned char combining = _getrecord_ex(code)->combining;
        Py_ssize_t j = i;

        while (j > start) {
            Py_UCS4 previous = data[j - 1];
            if (_getrecord_ex(previous)->combining <= combining) {
                break;
            }
            data[j] = previous;
            j--;
        }
        if (j != i) {
            data[j] = code;
        }
    }
}

static void
canonical_ordering_sort_counting(std::u32string& data,
                                 Py_ssize_t start, Py_ssize_t end,
                                 std::vector<Py_UCS4>& sortbuf)
{
    Py_ssize_t counts[256] = {0};
    Py_ssize_t run_length = end - start;
    Py_ssize_t total = 0;

    for (Py_ssize_t i = start; i < end; i++) {
        Py_UCS4 code = data[i];
        unsigned char combining = _getrecord_ex(code)->combining;
        counts[combining]++;
    }

    for (size_t i = 0; i < Py_ARRAY_LENGTH(counts); i++) {
        Py_ssize_t count = counts[i];
        counts[i] = total;
        total += count;
    }

    /* Reuse counts[] as the next output slot for each CCC. */
    for (Py_ssize_t i = start; i < end; i++) {
        Py_UCS4 code = data[i];
        unsigned char combining = _getrecord_ex(code)->combining;
        sortbuf[counts[combining]++] = code;
    }
    for (Py_ssize_t i = 0; i < run_length; i++) {
        data[start + i] = sortbuf[i];
    }
}

std::u32string
nfd_nfkd(bool old, std::u32string_view input, int k)
{
    std::u32string output;
    Py_ssize_t i, isize;
    /* Longest decomposition in Unicode 3.2: U+FDFA */
    Py_UCS4 stack[20];
    int index, prefix, count, stackptr;
    unsigned char prev, cur;
    std::vector<Py_UCS4> sortbuf;

    stackptr = 0;
    isize = static_cast<Py_ssize_t>(input.size());
    output.reserve(isize > 10 ? isize + 10 : isize * 2);   /* Overallocate at most 10 characters. */
    i = 0;

    while (i < isize) {
        stack[stackptr++] = input[i++];
        while(stackptr) {
            Py_UCS4 code = stack[--stackptr];
            // Hangul Decomposition.
            // See section 3.12.2, "Hangul Syllable Decomposition"
            // https://www.unicode.org/versions/latest/core-spec/chapter-3/#G56669
            if (SBase <= code && code < (SBase+SCount)) {
                int SIndex = code - SBase;
                int L = LBase + SIndex / NCount;
                int V = VBase + (SIndex % NCount) / TCount;
                int T = TBase + SIndex % TCount;
                output += static_cast<char32_t>(L);
                output += static_cast<char32_t>(V);
                if (T != TBase) {
                    output += static_cast<char32_t>(T);
                }
                continue;
            }
            /* normalization changes */
            if (old) {
                Py_UCS4 value = normalization_3_2_0(code);
                if (value != 0) {
                    stack[stackptr++] = value;
                    continue;
                }
            }

            /* Other decompositions. */
            get_decomp_record(old, code, &index, &prefix, &count);

            /* Copy character if it is not decomposable, or has a
               compatibility decomposition, but we do NFD. */
            if (!count || (prefix && !k)) {
                output += static_cast<char32_t>(code);
                continue;
            }
            if (stackptr + count > static_cast<int>(Py_ARRAY_LENGTH(stack)))   // the C's stack would overflow; the tables never ask it to
                throw NotImplemented("unicodedata: a decomposition longer than the C's stack of 20");
            /* Copy decomposition onto the stack, in reverse
               order.  */
            while(count) {
                code = decomp_data[index + (--count)];
                stack[stackptr++] = code;
            }
        }
    }

    Py_ssize_t o = static_cast<Py_ssize_t>(output.size());
    /* Sort each consecutive combining-character run canonically. */
    i = 0;
    while (i < o) {
        Py_ssize_t run_length, run_start;
        int needs_sort = 0;

        Py_UCS4 ch = output[i];
        prev = _getrecord_ex(ch)->combining;
        if (prev == 0) {
            i++;
            continue;
        }

        run_start = i++;
        while (i < o) {
            Py_UCS4 ch = output[i];
            cur = _getrecord_ex(ch)->combining;
            if (cur == 0) {
                break;
            }
            if (prev > cur) {
                needs_sort = 1;
            }
            prev = cur;
            i++;
        }
        if (!needs_sort) {
            continue;
        }

        run_length = i - run_start;
        if (run_length < CANONICAL_ORDERING_COUNTING_SORT_THRESHOLD) {
            canonical_ordering_sort_insertion(output, run_start, i);
            continue;
        }

        if (run_length > static_cast<Py_ssize_t>(sortbuf.size())) {
            sortbuf.resize(run_length);
        }

        canonical_ordering_sort_counting(output, run_start, i, sortbuf);
    }
    return output;
}

static int
find_nfc_index(const struct reindex* nfc, Py_UCS4 code)
{
    unsigned int index;
    for (index = 0; nfc[index].start; index++) {
        unsigned int start = nfc[index].start;
        if (code < start)
            return -1;
        if (code <= start + nfc[index].count) {
            unsigned int delta = code - start;
            return nfc[index].index + delta;
        }
    }
    return -1;
}

std::u32string
nfc_nfkc(bool old, std::u32string_view input, int k)
{
    Py_ssize_t i, i1, o, len;
    int f,l,index,index1,comb;
    Py_UCS4 code;
    Py_ssize_t skipped[20];
    int cskipped = 0;

    std::u32string data = nfd_nfkd(old, input, k);
    len = static_cast<Py_ssize_t>(data.size());

    /* We allocate a buffer for the output.
       If we find that we made no changes, we still return
       the NFD result. */
    std::u32string output(len, U'\0');
    i = o = 0;

    while (i < len) {
      bool was_skipped = false;                 // the C's `goto again`, a continue of this loop
      for (index = 0; index < cskipped; index++) {
          if (skipped[index] == i) {
              /* *i character is skipped.
                 Remove from list. */
              skipped[index] = skipped[cskipped-1];
              cskipped--;
              i++;
              was_skipped = true;
              break;
          }
      }
      if (was_skipped)
          continue;
      /* Hangul Composition. We don't need to check for <LV,T>
         pairs, since we always have decomposed data. */
      code = data[i];
      if (LBase <= code && code < (LBase+LCount) &&
          i + 1 < len &&
          VBase <= data[i+1] &&
          data[i+1] < (VBase+VCount)) {
          /* check L character is a modern leading consonant (0x1100 ~ 0x1112)
             and V character is a modern vowel (0x1161 ~ 0x1175). */
          int LIndex, VIndex;
          LIndex = code - LBase;
          VIndex = data[i+1] - VBase;
          code = SBase + (LIndex*VCount+VIndex)*TCount;
          i+=2;
          if (i < len &&
              TBase < data[i] &&
              data[i] < (TBase+TCount)) {
              /* check T character is a modern trailing consonant
                 (0x11A8 ~ 0x11C2). */
              code += data[i]-TBase;
              i++;
          }
          output[o++] = code;
          continue;
      }

      /* code is still input[i] here */
      f = find_nfc_index(nfc_first, code);
      if (f == -1) {
          output[o++] = code;
          i++;
          continue;
      }
      /* Find next unblocked character. */
      i1 = i+1;
      comb = 0;
      /* output base character for now; might be updated later. */
      output[o] = data[i];
      while (i1 < len) {
          Py_UCS4 code1 = data[i1];
          int comb1 = _getrecord_ex(code1)->combining;
          if (comb) {
              if (comb1 == 0)
                  break;
              if (comb >= comb1) {
                  /* Character is blocked. */
                  i1++;
                  continue;
              }
          }
          l = find_nfc_index(nfc_last, code1);
          /* i1 cannot be combined with i. If i1
             is a starter, we don't need to look further.
             Otherwise, record the combining class. */
          code = 0;                             // the C's `goto not_combinable` from a zero in comp_data, folded into this test
          if (l != -1) {
              index = f*TOTAL_LAST + l;
              index1 = comp_index[index >> COMP_SHIFT];
              code = comp_data[(index1<<COMP_SHIFT)+
                               (index&((1<<COMP_SHIFT)-1))];
          }
          if (code == 0) {
            /* not_combinable: */
              if (comb1 == 0)
                  break;
              comb = comb1;
              i1++;
              continue;
          }

          /* Replace the original character. */
          output[o] = code;
          /* Mark the second character unused. */
          if (cskipped >= 20)                   // the C asserts it; the tables never reach it
              throw NotImplemented("unicodedata: more than 20 characters composed into one (the C's skipped list)");
          skipped[cskipped++] = i1;
          i1++;
          f = find_nfc_index(nfc_first, output[o]);
          if (f == -1)
              break;
      }
      /* Output character was already written.
         Just advance the indices. */
      o++; i++;
    }
    if (o == len) {
        /* No changes. Return original string. */
        return data;
    }
    output.resize(o);
    return output;
}

// This needs to match the logic in makeunicodedata.py
// which constructs the quickcheck data.
typedef enum {YES = 0, MAYBE = 1, NO = 2} QuickcheckResult;

/* Run the Unicode normalization "quickcheck" algorithm.
 *
 * Return YES or NO if quickcheck determines the input is certainly
 * normalized or certainly not, and MAYBE if quickcheck is unable to
 * tell.
 *
 * If `yes_only` is true, then return MAYBE as soon as we determine
 * the answer is not YES.
 *
 * For background and details on the algorithm, see UAX #15:
 *   https://www.unicode.org/reports/tr15/#Detecting_Normalization_Forms
 */
static QuickcheckResult
is_normalized_quickcheck(bool old, const Str* input, bool nfc, bool k,
                         bool yes_only)
{
    /* UCD 3.2.0 is requested, quickchecks must be disabled. */
    if (old) {
        return MAYBE;
    }

    if (input->ascii) {                         // PyUnicode_IS_ASCII
        return YES;
    }

    Py_ssize_t i, len;
    unsigned char prev_combining = 0;

    /* The two quickcheck bits at this shift have type QuickcheckResult. */
    int quickcheck_shift = (nfc ? 4 : 0) + (k ? 2 : 0);

    QuickcheckResult result = YES; /* certainly normalized, unless we find something */

    i = 0;
    len = static_cast<Py_ssize_t>(input->length);
    while (i < len) {
        Py_UCS4 ch = input->at(i++);
        const _PyUnicode_DatabaseRecord *record = _getrecord_ex(ch);

        unsigned char combining = record->combining;
        if (combining && prev_combining > combining)
            return NO; /* non-canonical sort order, not normalized */
        prev_combining = combining;

        unsigned char quickcheck_whole = record->normalization_quick_check;
        if (yes_only) {
            if (quickcheck_whole & (3 << quickcheck_shift))
                return MAYBE;
        } else {
            switch ((quickcheck_whole >> quickcheck_shift) & 3) {
            case NO:
              return NO;
            case MAYBE:
              result = MAYBE; /* this string might need normalization */
            }
        }
    }
    return result;
}

std::u32string code_points(const Str* s) {
    std::u32string out;
    out.reserve(s->length);
    for (std::size_t i = 0; i < s->length; ++i) out += s->at(i);
    return out;
}

Ref from_object(Obj input) {                    // PyUnicode_FromObject: the str itself, a subclass's as a new str
    return is_exact_str(input) ? Ref::share(input) : str_new(as_str(input)->text);
}

bool form_is(Obj form, const char* name) { return as_str(form)->text == name; }   // PyUnicode_CompareWithASCIIString(form, name) == 0

Ref is_normalized(bool old, Obj form, Obj input_obj)   // unicodedata_UCD_is_normalized_impl
{
    const Str* input = as_str(input_obj);
    if (input->length == 0) {
        /* special case empty input strings. */
        return Ref::steal(boolean(true));
    }

    bool nfc = false;
    bool k = false;
    QuickcheckResult m;

    if (form_is(form, "NFC")) {
        nfc = true;
    }
    else if (form_is(form, "NFKC")) {
        nfc = true;
        k = true;
    }
    else if (form_is(form, "NFD")) {
        /* matches default values for `nfc` and `k` */
    }
    else if (form_is(form, "NFKD")) {
        k = true;
    }
    else {
        raise_new("ValueError", "invalid normalization form");
    }

    m = is_normalized_quickcheck(old, input, nfc, k, false);

    if (m == MAYBE) {
        std::u32string text = code_points(input);
        std::u32string cmp = nfc ? nfc_nfkc(old, text, k) : nfd_nfkd(old, text, k);
        return Ref::steal(boolean(cmp == text));
    }
    return Ref::steal(boolean(m == YES));
}

Ref normalize(bool old, Obj form, Obj input_obj)   // unicodedata_UCD_normalize_impl
{
    const Str* input = as_str(input_obj);
    if (input->length == 0) {
        /* Special case empty input strings, since resizing
           them  later would cause internal errors. */
        return from_object(input_obj);
    }

    if (form_is(form, "NFC")) {
        if (is_normalized_quickcheck(old, input,
                                     true,  false, true) == YES) {
            return from_object(input_obj);
        }
        return str_from_codepoints(nfc_nfkc(old, code_points(input), 0));
    }
    if (form_is(form, "NFKC")) {
        if (is_normalized_quickcheck(old, input,
                                     true,  true,  true) == YES) {
            return from_object(input_obj);
        }
        return str_from_codepoints(nfc_nfkc(old, code_points(input), 1));
    }
    if (form_is(form, "NFD")) {
        if (is_normalized_quickcheck(old, input,
                                     false, false, true) == YES) {
            return from_object(input_obj);
        }
        return str_from_codepoints(nfd_nfkd(old, code_points(input), 0));
    }
    if (form_is(form, "NFKD")) {
        if (is_normalized_quickcheck(old, input,
                                     false, true,  true) == YES) {
            return from_object(input_obj);
        }
        return str_from_codepoints(nfd_nfkd(old, code_points(input), 1));
    }
    raise_new("ValueError", "invalid normalization form");
}

