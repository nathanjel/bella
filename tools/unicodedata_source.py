"""CPython's generated Unicode databases as C text for the runtime (runtime/src/unicode*_db.inc, licence register L-03).

    python tools/unicodedata_source.py PATH_TO_CPYTHON_SOURCE            write the files
    python tools/unicodedata_source.py PATH_TO_CPYTHON_SOURCE --check    fail if the committed files are not what that source gives

The source tree is the pin's release (Python-3.15.2.tar.xz from python.org, SHA-256
8b5536d280142ecf6cdfe15d12a21ba1c65e300bbf7b28a8d0cdb849575797de), which neither the repository nor the image holds: this runs
by hand when the pin moves, as tools/tokenizer_source.py does. Tools/unicode/makeunicodedata.py wrote the three headers from
Unicode 17.0.0's data files: Modules/unicodedata_db.h (the module's records, decompositions, compositions, the names of the
properties, the blocks, and the changes back to 3.2.0), Modules/unicodename_db.h (the names, as a packed DAWG, the aliases and
the named sequences) and Objects/unicodetype_db.h (str's records: the decimal and digit values, the flags, the numeric values).
runtime/src/unicodedata.cpp includes each once, after the types the C defines for it. Each file is the header's text whole, under
a comment that says where it came from; this script changes nothing in it.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
FILES = (("Modules/unicodedata_db.h", "unicodedata_db.inc", "the module's records (Modules/unicodedata.c's _PyUnicode_DatabaseRecord), "
          "the decompositions and compositions, the names of the properties, the blocks, the changes back to Unicode 3.2.0"),
         ("Modules/unicodename_db.h", "unicodename_db.inc", "the character names as a packed DAWG, the derived names' ranges, the "
          "aliases and the named sequences (Modules/unicodedata.c reads them)"),
         ("Objects/unicodetype_db.h", "unicodetype_db.inc", "str's records (Objects/unicodectype.c's _PyUnicode_TypeRecord): the "
          "decimal and digit values, the flags, and _PyUnicode_ToNumeric"))


def render(source: Path, header: str, what: str) -> str:
    text = (source / header).read_text(encoding="utf-8")
    return (f"// CPython 3.15.2's {header}, whole (licence register L-03): {what}.\n"
            f"// Generated by Tools/unicode/makeunicodedata.py from Unicode 17.0.0's data files; copied by tools/unicodedata_source.py\n"
            f"// from the pin's release, unchanged. runtime/src/unicodedata.cpp includes it once.\n\n" + text)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    ap.add_argument("source", type=Path, help="the pin's source tree (Python-3.15.2)")
    ap.add_argument("--check", action="store_true", help="fail if the committed files are not what the source gives")
    args = ap.parse_args(argv)
    failed = False
    for header, name, what in FILES:
        out = PROJECT / "runtime" / "src" / name
        text = render(args.source, header, what)
        if args.check:
            if not out.exists() or out.read_text(encoding="utf-8") != text:
                print(f"unicodedata_source: {out} is not what {args.source}/{header} gives", file=sys.stderr)
                failed = True
            else:
                print(f"unicodedata_source: {name} agrees with {args.source.name}/{header}")
            continue
        out.write_text(text, encoding="utf-8")
        print(f"unicodedata_source: wrote {name} ({len(text.splitlines())} lines) from {args.source.name}/{header}")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
