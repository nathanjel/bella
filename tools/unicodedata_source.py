"""CPython's generated Unicode databases as C text for the runtime (runtime/src/unicode*_db.inc, licence register L-03).

    python tools/unicodedata_source.py SOURCE            write the files
    python tools/unicodedata_source.py SOURCE --check    fail if the committed files are not what that source gives

SOURCE is the pin's release: the archive itself (Python-3.15.2.tar.xz from python.org), whose SHA-256 is checked against
ARCHIVE_SHA256 below, or a tree extracted from it. Neither the repository nor the image holds it: this runs by hand when the
pin moves, as tools/tokenizer_source.py does. A source that is not the pin's release (Include/patchlevel.h against
manifest.toml's [reference]) is refused. Tools/unicode/makeunicodedata.py wrote the three headers from the Unicode data
files: Modules/unicodedata_db.h (the module's records, decompositions, compositions, the names of the properties, the
blocks, and the changes back to 3.2.0), Modules/unicodename_db.h (the names, as a packed DAWG, the aliases and the named
sequences) and Objects/unicodetype_db.h (str's records: the decimal and digit values, the flags, the numeric values).
runtime/src/unicodedata.cpp includes each once, after the types the C defines for it. Each file is the header's text whole,
under a comment that says where it came from, with the release and the Unicode version read from the source; this script
changes nothing in it. The prelude takes UNIDATA_VERSION and NAME_MAXLEN from the copied text through the runtime, and
tools/tests/test_unicodedata_source.py holds the committed files to the pin.
"""
from __future__ import annotations

import argparse
import hashlib
import re
import sys
import tarfile
import tomllib
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
# the pin's release archive: moves with manifest.toml's [reference]
ARCHIVE_SHA256 = "8b5536d280142ecf6cdfe15d12a21ba1c65e300bbf7b28a8d0cdb849575797de"
FILES = (("Modules/unicodedata_db.h", "unicodedata_db.inc", "the module's records (Modules/unicodedata.c's _PyUnicode_DatabaseRecord), "
          "the decompositions and compositions, the names of the properties, the blocks, the changes back to Unicode 3.2.0"),
         ("Modules/unicodename_db.h", "unicodename_db.inc", "the character names as a packed DAWG, the derived names' ranges, the "
          "aliases and the named sequences (Modules/unicodedata.c reads them)"),
         ("Objects/unicodetype_db.h", "unicodetype_db.inc", "str's records (Objects/unicodectype.c's _PyUnicode_TypeRecord): the "
          "decimal and digit values, the flags, and _PyUnicode_ToNumeric"))
RELEASE_HEADER = "Include/patchlevel.h"


def pinned() -> str:
    """The reference release (manifest.toml [reference])."""
    return str(tomllib.loads((PROJECT / "manifest.toml").read_text(encoding="utf-8"))["reference"]["python"])


def read_source(source: Path) -> dict[str, str]:
    """The headers' texts and the release header's, from an extracted tree or from the release archive, whose hash is checked."""
    wanted = [header for header, _, _ in FILES] + [RELEASE_HEADER]
    if source.is_dir():
        return {name: (source / name).read_text(encoding="utf-8") for name in wanted}
    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    if digest != ARCHIVE_SHA256:
        raise SystemExit(f"unicodedata_source: {source} has SHA-256 {digest}, the pin's release archive has {ARCHIVE_SHA256}")
    texts: dict[str, str] = {}
    with tarfile.open(source) as archive:
        for member in archive:
            name = member.name.partition("/")[2]          # under the archive's one directory
            if name in wanted:
                data = archive.extractfile(member)
                assert data is not None
                texts[name] = data.read().decode("utf-8")
    missing = sorted(set(wanted) - set(texts))
    if missing:
        raise SystemExit(f"unicodedata_source: {source} has no {', '.join(missing)}")
    return texts


def defined(text: str, macro: str) -> str:
    """The string a header defines a macro as."""
    found = re.search(rf'^#define {macro}\s+"([^"]+)"', text, re.MULTILINE)
    if found is None:
        raise SystemExit(f"unicodedata_source: no #define {macro} in the source")
    return found.group(1)


def render(texts: dict[str, str], header: str, what: str) -> str:
    release = defined(texts[RELEASE_HEADER], "PY_VERSION")
    unidata = defined(texts[FILES[0][0]], "UNIDATA_VERSION")
    return (f"// CPython {release}'s {header}, whole (licence register L-03): {what}.\n"
            f"// Generated by Tools/unicode/makeunicodedata.py from Unicode {unidata}'s data files; copied by tools/unicodedata_source.py\n"
            f"// from the pin's release, unchanged. runtime/src/unicodedata.cpp includes it once.\n\n" + texts[header])


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    ap.add_argument("source", type=Path, help="the pin's release: Python-X.Y.Z.tar.xz, or a tree extracted from it")
    ap.add_argument("--check", action="store_true", help="fail if the committed files are not what the source gives")
    args = ap.parse_args(argv)
    texts = read_source(args.source)
    release = defined(texts[RELEASE_HEADER], "PY_VERSION")
    if release != pinned():
        print(f"unicodedata_source: {args.source} is CPython {release}, the pin is {pinned()}", file=sys.stderr)
        return 1
    failed = False
    for header, name, what in FILES:
        out = PROJECT / "runtime" / "src" / name
        text = render(texts, header, what)
        if args.check:
            if not out.exists() or out.read_text(encoding="utf-8") != text:
                print(f"unicodedata_source: {out} is not what {args.source}/{header} gives", file=sys.stderr)
                failed = True
            else:
                print(f"unicodedata_source: {name} agrees with {args.source.name}/{header}")
            continue
        out.write_text(text, encoding="utf-8")
        print(f"unicodedata_source: wrote {name} ({len(text.splitlines())} lines) from {args.source.name}/{header}")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
