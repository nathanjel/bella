"""The Unicode tables the compiled runtime reads, from the pinned CPython (licence register L-03).

`_sre`'s categories and case mappings come from CPython's own, Py_UNICODE_ISALNUM and the others: this asks the pin for each code
point and writes `runtime/src/unicode_tables.inc` as ranges and pairs, committed like the conformance expectations. `--check` fails when
the pinned CPython disagrees (`make verify`); `--allow-unpinned` runs on another Python, for development only. A case mapping is the
first character of the full one, which is what `_PyUnicode_ToLowercase` returns; this checks that against `_sre` for every code point.
"""
from __future__ import annotations

import argparse
import sys
import tomllib
from collections.abc import Callable
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
OUT = PROJECT / "runtime" / "src" / "unicode_tables.inc"
LAST = 0x10FFFF


def pinned_python() -> str:
    return str(tomllib.loads((PROJECT / "bella.toml").read_text(encoding="utf-8"))["reference"]["python"])


def ranges(belongs: Callable[[int], bool]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    start: int | None = None
    for c in range(LAST + 1):
        if belongs(c):
            if start is None:
                start = c
        elif start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, LAST))
    return out


def render() -> str:
    import _sre  # type: ignore[import-not-found]

    def lower(c: int) -> int:
        return ord(chr(c).lower()[0])

    def upper(c: int) -> int:
        return ord(chr(c).upper()[0])

    for c in range(LAST + 1):
        if lower(c) != _sre.unicode_tolower(c) or ((c != lower(c) or c != upper(c)) != bool(_sre.unicode_iscased(c))):
            raise SystemExit(f"unicode_tables: the case rule does not hold at U+{c:04X}")
    version = ".".join(map(str, sys.version_info[:3]))
    lines = [f"// Generated by tools/unicode_tables.py from CPython {version}; do not edit. Unicode's data (licence register L-03), as CPython has it:",
             "// what `Py_UNICODE_ISALNUM`, `ISDECIMAL`, `ISSPACE`, `ISLINEBREAK`, `ISPRINTABLE` and the others say, in ranges, the first character of the case mappings that change a code point (`_sre`'s), and the full mappings, sorted.",
             "struct CodePointRange {", "    std::uint32_t first, last;", "};", "struct CaseMapping {", "    std::uint32_t from, to;", "};"]
    tables: dict[str, list[tuple[int, int]]] = {
        "UNICODE_ALNUM": ranges(lambda c: chr(c).isalnum()),
        "UNICODE_DECIMAL": ranges(lambda c: chr(c).isdecimal()),
        "UNICODE_SPACE": ranges(lambda c: chr(c).isspace()),
        "UNICODE_LINEBREAK": ranges(lambda c: len(("a" + chr(c) + "b").splitlines()) == 2),
        "UNICODE_PRINTABLE": ranges(lambda c: chr(c).isprintable()),
        "UNICODE_XID_START": ranges(lambda c: c != 0x5F and chr(c).isidentifier()),
        "UNICODE_XID_CONTINUE": ranges(lambda c: ("a" + chr(c)).isidentifier()),
        # str's predicates and case conversions (Objects/unicodeobject.c): a one-character str answers with the flag itself,
        # except istitle, which answers ISTITLE or ISUPPER
        "UNICODE_ALPHA": ranges(lambda c: chr(c).isalpha()),
        "UNICODE_DIGIT": ranges(lambda c: chr(c).isdigit()),
        "UNICODE_NUMERIC": ranges(lambda c: chr(c).isnumeric()),
        "UNICODE_LOWERCASE": ranges(lambda c: chr(c).islower()),
        "UNICODE_UPPERCASE": ranges(lambda c: chr(c).isupper()),
        "UNICODE_TITLECASE": ranges(lambda c: chr(c).istitle() and not chr(c).isupper()),
        # _PyUnicode_IsCased, as do_title reads it: the letter after a cased one is lowered
        "UNICODE_CASED": ranges(lambda c: (chr(c) + "a").title()[-1] == "a"),
        # _PyUnicode_IsCaseIgnorable, as handle_capital_sigma reads it: an ignorable one between a cased letter and a final
        # sigma is passed over (the sigma is final), and alone before it is not a cased letter (it is not)
        "UNICODE_CASE_IGNORABLE": ranges(lambda c: ("A" + chr(c) + "\u03a3").lower()[-1] == "\u03c2" and (chr(c) + "\u03a3").lower()[-1] == "\u03c3"),
    }
    for name, table in tables.items():
        lines.append(f"static constexpr CodePointRange {name}[] = {{")
        lines += [f"    {{0x{a:X}, 0x{b:X}}}," for a, b in table]
        lines.append("};")
    for name, mapping in (("UNICODE_LOWER", lower), ("UNICODE_UPPER", upper)):
        lines.append(f"static constexpr CaseMapping {name}[] = {{")
        lines += [f"    {{0x{c:X}, 0x{mapping(c):X}}}," for c in range(LAST + 1) if mapping(c) != c]
        lines.append("};")
    # the full mappings, one to three code points (_PyUnicode_ToLowerFull and the others): a one-character str's lower(),
    # upper(), title() and casefold() are those, U+03A3's lower() too (no letter before it, so not a final sigma)
    lines.append("struct FullMapping {")
    lines.append("    std::uint32_t from;")
    lines.append("    std::uint8_t count;")
    lines.append("    std::uint32_t to[3];")
    lines.append("};")
    full: dict[str, Callable[[str], str]] = {"UNICODE_LOWER_FULL": str.lower, "UNICODE_UPPER_FULL": str.upper,
                                              "UNICODE_TITLE_FULL": str.title, "UNICODE_FOLD_FULL": str.casefold}
    for name, convert in full.items():
        lines.append(f"static constexpr FullMapping {name}[] = {{")
        for c in range(LAST + 1):
            mapped = convert(chr(c))
            if mapped != chr(c):
                if len(mapped) > 3:
                    raise SystemExit(f"unicode_tables: U+{c:04X} maps to more than three code points")
                cps = [ord(m) for m in mapped] + [0] * (3 - len(mapped))
                lines.append(f"    {{0x{c:X}, {len(mapped)}, {{0x{cps[0]:X}, 0x{cps[1]:X}, 0x{cps[2]:X}}}}},")
        lines.append("};")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if the file is not what the pinned CPython gives")
    ap.add_argument("--allow-unpinned", action="store_true", help="development only")
    args = ap.parse_args(argv)
    version = ".".join(map(str, sys.version_info[:3]))
    if not args.allow_unpinned and version != pinned_python():
        print(f"unicode_tables: run on CPython {pinned_python()}, this is {version}", file=sys.stderr)
        return 2
    text = render()
    if args.check:
        if OUT.read_text(encoding="utf-8") != text:
            print(f"unicode_tables: {OUT} disagrees with CPython {version}", file=sys.stderr)
            return 1
        print(f"unicode_tables: agree with CPython {version}")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"unicode_tables: wrote {OUT.name} from CPython {version}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
