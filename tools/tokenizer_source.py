"""CPython's tokenizer as one file of C text for the runtime (runtime/src/tokenizer_lexer.inc, licence register L-01).

    python tools/tokenizer_source.py PATH_TO_CPYTHON_SOURCE            write the file
    python tools/tokenizer_source.py PATH_TO_CPYTHON_SOURCE --check    fail if the committed file is not what that source gives

The source tree is the pin's release (Python-3.15.2.tar.xz from python.org, SHA-256
8b5536d280142ecf6cdfe15d12a21ba1c65e300bbf7b28a8d0cdb849575797de), which neither the repository nor the image holds: this runs
by hand when the pin moves. The file is the C's text in the order runtime/src/tokenizer.cpp needs it: the error codes, the token
numbers, lexer/state.h, tokenizer/helpers.h, lexer/state.c, lexer/buffer.c, the operator functions of token.c and lexer/lexer.c.
What differs from the C is in the header it writes, and is all this script does to the text."""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
OUT = PROJECT / "runtime" / "src" / "tokenizer_lexer.inc"

HEADER = '''// CPython 3.15.2's tokenizer, as C text that compiles as C++ (licence register L-01): Include/errcode.h's codes, the token numbers
// of Include/internal/pycore_token.h, then Parser/lexer/state.h, Parser/tokenizer/helpers.h, Parser/lexer/state.c,
// Parser/lexer/buffer.c, the three operator functions of Parser/token.c and Parser/lexer/lexer.c, each whole and in that order.
// Generated by tools/tokenizer_source.py from the pin's release; runtime/src/tokenizer.cpp includes it once, after the few names
// of CPython's API it uses (PyMem_*, PyUnicode_DecodeUTF8 and the like, the error indicator), and gives it the functions
// helpers.h declares. What differs from the C: the #include lines and the header guards are gone, and _PyTokenizer_tok_new's
// compound literal is two statements. Py_DEBUG is not defined, so the debug branches fall away as written.
'''


def body(text: str) -> str:
    """A file's text without its #include lines."""
    return "\n".join(line for line in text.split("\n") if not re.match(r"\s*#\s*include\b", line)).strip("\n") + "\n"


def header_body(text: str, guard: str) -> str:
    """A header's text without its #include lines and its guard."""
    text = body(text)
    opening = f"#ifndef {guard}\n#define {guard}\n"
    if opening not in text or not text.rstrip().endswith("#endif"):
        raise SystemExit(f"tokenizer_source: {guard} is not guarded as expected")
    return text.replace(opening, "").rstrip()[: -len("#endif")].rstrip("\n") + "\n"


def render(source: Path) -> str:
    def read(relative: str) -> str:
        return (source / relative).read_text(encoding="utf-8")

    errcode = "\n".join(line for line in read("Include/errcode.h").split("\n") if line.startswith("#define E_")) + "\n"
    tokens_h = read("Include/internal/pycore_token.h")
    tokens = tokens_h[tokens_h.index("#define ENDMARKER"):tokens_h.index("// Export these 4 symbols")].rstrip("\n") + "\n"
    state_c = body(read("Parser/lexer/state.c"))
    literal = "    tok->tok_mode_stack[0] = (tokenizer_mode){.kind =TOK_REGULAR_MODE, .quote='\\0', .quote_size = 0, .in_debug=0};\n"
    if state_c.count(literal) != 1:
        raise SystemExit("tokenizer_source: _PyTokenizer_tok_new's compound literal is not as expected")
    state_c = state_c.replace(literal, "    tok->tok_mode_stack[0] = tokenizer_mode{};   /* bella: a compound literal in the C; the members it names are these */\n"
                                       "    tok->tok_mode_stack[0].kind = TOK_REGULAR_MODE;\n")
    token_c = read("Parser/token.c")
    operators = token_c[token_c.index("/* Return the token corresponding to a single character */"):].rstrip("\n") + "\n"
    sections = [("Include/errcode.h", errcode), ("Include/internal/pycore_token.h", tokens),
                ("Parser/lexer/state.h", header_body(read("Parser/lexer/state.h"), "_PY_LEXER_H_")),
                ("Parser/tokenizer/helpers.h", header_body(read("Parser/tokenizer/helpers.h"), "_PY_TOKENIZER_HELPERS_H_")),
                ("Parser/lexer/state.c", state_c), ("Parser/lexer/buffer.c", body(read("Parser/lexer/buffer.c"))),
                ("Parser/token.c", operators), ("Parser/lexer/lexer.c", body(read("Parser/lexer/lexer.c")))]
    return HEADER + "".join(f"\n/* ======== {name} ======== */\n\n{text}" for name, text in sections)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    ap.add_argument("source", type=Path, help="the pin's source tree (Python-3.15.2)")
    ap.add_argument("--check", action="store_true", help="fail if the committed file is not what the source gives")
    args = ap.parse_args(argv)
    text = render(args.source)
    if args.check:
        if OUT.read_text(encoding="utf-8") != text:
            print(f"tokenizer_source: {OUT} is not what {args.source} gives", file=sys.stderr)
            return 1
        print(f"tokenizer_source: {OUT.name} agrees with {args.source.name}")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"tokenizer_source: wrote {OUT.name} ({len(text.splitlines())} lines) from {args.source.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
